/**
 * Defina a base e a altura de um retângulo; calcule e mostre a área (base * altura)
 * e o  perímetro (2 x base + altura)
 */


const base = 10
const altura = 15


const areaRetangulo = (base * altura)
const perimetro = 2 * (base + altura)

console.log(`Área do retângulo: ${areaRetangulo} m²`)
console.log(`Perímetro do retângulo:${perimetro}m`)